#!/usr/bin/env node
// Generates mvp1/index.html from web/index.html.
//
// MVP1 is the same app restricted to the Import Fixtures page. It shares all
// CSS/JS with /web/ (via <base href="../web/">), so the only thing that differs
// is this generated HTML shell. Never edit mvp1/index.html by hand.
//
// Run after `npm run cache-bust` so the copied ?v= stamps are current.
//
// Usage:
//   node scripts/build-mvp1.mjs          regenerate mvp1/index.html
//   node scripts/build-mvp1.mjs --check  exit 1 if mvp1/index.html is stale (CI)

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(rootDir, 'web', 'index.html');
const targetPath = path.join(rootDir, 'mvp1', 'index.html');
const checkOnly = process.argv.includes('--check');

// data-page-index of each page enabled in MVP1. 1 = Import Fixtures.
const MVP1_PAGES = [1];
// Import Fixtures filter mode: no free-text search, mandatory Sport → Date range
// → Fixture group, with groups loaded from the API for the sport + dates.
const MVP1_IMPORT_FILTER_MODE = 'guided';
// Import Fixtures table columns (keys of FIXTURE_COLUMN_DEFS in the core).
const MVP1_FIXTURE_COLUMNS = ['fixture', 'group', 'sport', 'scheduledStartDate', 'elapsedTime', 'createdDate', 'updatedDate', 'id'];

function replaceOnce(source, pattern, replacement, label) {
  if (!pattern.test(source)) throw new Error(`build-mvp1: could not find ${label} in web/index.html`);
  return source.replace(pattern, replacement);
}

const source = await fs.readFile(sourcePath, 'utf8');
let output = source;
output = replaceOnce(output, /<html lang="en">/, `<html lang="en" data-enabled-pages="${MVP1_PAGES.join(',')}" data-import-filter-mode="${MVP1_IMPORT_FILTER_MODE}" data-fixture-columns="${MVP1_FIXTURE_COLUMNS.join(',')}">`, '<html lang="en">');
output = replaceOnce(output, /<meta charset="UTF-8">/, [
  '<!-- GENERATED by scripts/build-mvp1.mjs from web/index.html. Do not edit. -->',
  '<meta charset="UTF-8">',
  '<base href="../web/">'
].join('\n'), '<meta charset="UTF-8">');
output = replaceOnce(output, /<title>([^<]*)<\/title>/, '<title>$1 (MVP1)</title>', '<title>');

const current = await fs.readFile(targetPath, 'utf8').catch(() => null);

if (checkOnly) {
  if (current !== output) {
    console.error('mvp1/index.html is out of date. Run: npm run build:mvp1');
    process.exit(1);
  }
  console.log('mvp1/index.html is up to date.');
} else if (current === output) {
  console.log('mvp1/index.html already up to date.');
} else {
  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, output);
  console.log('Generated mvp1/index.html.');
}
